ENV_NAME = ".env.initrd-flash"
PRESIGN_NAME = ".presigning-vars"

# The tegraflash-bsp recipe's heredoc, expanded for a qemu-free Orin Nano build.
GENERATED = """# Environment settings for initrd-flash
# Generated by tegraflash-bsp recipe
MACHINE="avocado-jetson-orin-nano"
DTBFILE="tegra234-p3768-0000+p3767-0005-nv.dtb"
ROOTFS_IMAGE="avocado-image-rootfs-avocado-jetson-orin-nano.erofs-lz4"
LNXFILE="boot.img"
EMC_BCT="tegra234-mb1-bct-memcfg-p3767-0000.dtsi"
ODMDATA="gbe-uphy-config-8,hsstp-lane-map-3,hsio-uphy-lane-map-0000000"
CHIPID="0x23"
FLASH_HELPER="tegra234-flash-helper"
TOSIMGFILENAME="tos-optee_t234.img"
BOOTDEV="mmcblk0p1"
ROOTFS_DEVICE="nvme0n1"
EXTERNAL_ROOTFS_DRIVE=1
NO_INTERNAL_STORAGE=1
DATAFILE="avocado-image-var-avocado-jetson-orin-nano.btrfs"
"""


def read(tmp_path, text, presign=None):
    path = tmp_path / ENV_NAME
    path.write_text(text)
    if presign is not None:
        (tmp_path / PRESIGN_NAME).write_text(presign)
    return read_plain_env(path)


def refused(tmp_path, text, presign=None):
    with pytest.raises(EngineError) as exc:
        read(tmp_path, text, presign)
    return str(exc.value)


def test_a_real_generated_file_is_accepted_and_every_checked_key_is_read(tmp_path):
    assert read(tmp_path, GENERATED) == {
        "ROOTFS_IMAGE": "avocado-image-rootfs-avocado-jetson-orin-nano.erofs-lz4",
        "ROOTFS_DEVICE": "nvme0n1",
        "DATAFILE": "avocado-image-var-avocado-jetson-orin-nano.btrfs",
        "EXTERNAL_ROOTFS_DRIVE": "1",
        "NO_INTERNAL_STORAGE": "1",
        "TOSIMGFILENAME": "tos-optee_t234.img",
    }


def test_plain_assignments_are_read_with_quotes_removed(tmp_path):
    env = read(tmp_path, 'ROOTFS_IMAGE="r.img"\nROOTFS_DEVICE=nvme0n1\nDATAFILE=\'v.img\'\nOTHER=1\n')
    assert env == {"ROOTFS_IMAGE": "r.img", "ROOTFS_DEVICE": "nvme0n1", "DATAFILE": "v.img"}


def test_the_last_plain_assignment_wins(tmp_path):
    assert read(tmp_path, "ROOTFS_IMAGE=a.img\nROOTFS_IMAGE=b.img\n") == {"ROOTFS_IMAGE": "b.img"}


def test_absent_keys_are_absent_from_the_result(tmp_path):
    assert read(tmp_path, "BOOTDEV=x\n") == {}


def test_a_similarly_named_variable_is_not_the_key(tmp_path):
    assert read(tmp_path, "MY_ROOTFS_IMAGE=a\nROOTFS_IMAGE_X=b\nDATAFILE_B=c\n") == {}


def test_a_comment_mentioning_a_key_is_not_an_assignment(tmp_path):
    assert read(tmp_path, "# ROOTFS_IMAGE=a.img\n  # export ROOTFS_DEVICE=x\n") == {}


def test_a_read_of_a_key_is_allowed_in_both_spellings(tmp_path):
    text = 'ROOTFS_IMAGE=a.img\nX=$ROOTFS_IMAGE\nY="${ROOTFS_IMAGE}"\n'
    assert read(tmp_path, text) == {"ROOTFS_IMAGE": "a.img"}


